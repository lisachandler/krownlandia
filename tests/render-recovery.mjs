handlers.webglcontextrestored();assert.equal(resets,2);assert(get('#error').hidden);assert.equal(scheduled,beforeLoss+1);
handlers.webglcontextrestored();assert.equal(scheduled,beforeLoss+1,'duplicate restore cannot queue another frame');
