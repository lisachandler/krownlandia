import assert from 'node:assert/strict';
import * as T from '../dist/vendor/three.module.js';
import {installNavigation} from '../dist/navigation.js';
const scene=new T.Scene(),navigate=installNavigation({scene,blocked:(x,z)=>x>4&&x<8});
assert.equal(navigate(0,{x:0,z:0},{x:12,z:0},true).unreachable,true);
assert.equal(scene.getObjectByName('Walking guidance trail').visible,false);
const reachable=navigate(2000,{x:10,z:0},{x:12,z:0},true);assert(!reachable.unreachable);assert(Number.isFinite(reachable.distance));
assert.equal(navigate(2100,{x:10,z:0},{x:12,z:0},false),null);assert(!scene.getObjectByName('Walking guidance trail').visible);
assert.equal(navigate(2200,{x:10,z:0},null,true),null);
console.log('PASS: no-route status, recovery from a reachable position and hiding/clearing trail.');

const openScene=new T.Scene(),guide=installNavigation({scene:openScene,blocked:()=>false});
const trail=openScene.getObjectByName('Walking guidance trail');
const target={x:0,z:20},start={x:0,z:0};
const before=guide(0,start,target,true),version=trail.instanceMatrix.version,count=trail.count;
assert(trail.visible&&count>3);
const snapshot=Array.from(trail.instanceMatrix.array.slice(0,count*16));
const breathingRoom=guide(16,{x:.1,z:0},target,true);
assert.deepEqual(breathingRoom.next,before.next);assert(breathingRoom.distance>before.distance);
assert.equal(trail.instanceMatrix.version,version);
assert.deepEqual(Array.from(trail.instanceMatrix.array.slice(0,count*16)),snapshot);
guide(32,start,target,false);assert.equal(trail.visible,false);
guide(48,start,target,true);assert.equal(trail.instanceMatrix.version,version);
guide(64,{x:0,z:1},target,true);guide(80,{x:0,z:2},target,true);
const advanced=guide(96,{x:0,z:3},target,true);
assert(advanced.distance<before.distance&&trail.count<count);
assert(trail.instanceMatrix.version>version);
const movedVersion=trail.instanceMatrix.version;
guide(112,{x:0,z:3},{x:8,z:3},true);
assert(trail.visible&&trail.instanceMatrix.version>movedVersion);
console.log('PASS: unchanged and re-shown trail reuses transforms; distance still updates; walking and new directions update markers.');

const hiddenScene=new T.Scene(),hiddenGuide=installNavigation({scene:hiddenScene,blocked:(x,z)=>x>4&&x<8});
const hiddenTrail=hiddenScene.getObjectByName('Walking guidance trail'),versionBefore=hiddenTrail.instanceMatrix.version;
assert.deepEqual(hiddenGuide(0,{x:3,z:0},{x:8.2,z:0},false,true),{unreachable:true});
assert.equal(hiddenTrail.visible,false);
const hiddenTarget={x:11.3,z:0},near=hiddenGuide(2000,{x:9,z:0},hiddenTarget,false,true);
assert(near.distance>0&&near.distance<2.4);
assert.equal(hiddenTrail.visible,false);
assert.equal(hiddenTrail.instanceMatrix.version,versionBefore);
assert.deepEqual(hiddenGuide(2016,{x:9,z:0},hiddenTarget,true,true),near);
assert(hiddenTrail.visible);
assert(hiddenTrail.instanceMatrix.version>versionBefore);
assert.equal(hiddenGuide(2032,{x:9,z:0},hiddenTarget,false,false),null);
assert.equal(hiddenTrail.visible,false);
console.log('PASS: hidden active directions retain route status and distance without writing marker transforms; pausing still stops guidance.');
