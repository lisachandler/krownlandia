import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {installPizzaPuzzle} from '../dist/reports/pizza-sharing.js';
const page=readFileSync(new URL('../dist/reports/pizza-sharing.html',import.meta.url),'utf8');
assert.match(page,/Loreto’s Pizzeria, credited to @laloreto/);
assert.match(page,/<details><summary>Read one solution<\/summary>/);
assert.deepEqual([...page.matchAll(/data-slice="(\d)"[^>]+>\d · (\w+)/g)].map(([,n,t])=>[+n,t]),[[1,'Mushroom'],[2,'Pepper'],[3,'Mushroom'],[4,'Pepper'],[5,'Pepper'],[6,'Mushroom'],[7,'Pepper'],[8,'Mushroom']]);
let focused;
const tiles=Array.from({length:8},(_,i)=>({dataset:{slice:i+1},setAttribute(k,v){this[k]=v},focus(){focused=i}}));
const status={},check={},reset={},nodes={'#pizzaStatus':status,'#pizzaCheck':check,'#pizzaReset':reset};
const panel={open:false,hidden:true,querySelectorAll:()=>tiles,querySelector:key=>nodes[key]};
installPizzaPuzzle(panel);
tiles[0].onclick();assert.match(status.textContent,/no slices/);panel.open=true;
const choose=ns=>{reset.onclick();ns.forEach(n=>tiles[n-1].onclick());check.onclick();};
choose([1,2,3]);assert.match(status.textContent,/Choose four slices/);
choose([1,3,6,8]);assert.match(status.textContent,/Choose two of each topping/);
choose([1,2,5,6]);assert.match(status.textContent,/opposite pair on this plate/);
choose([1,2,3,4]);assert.match(status.textContent,/Both plates work/);
tiles[4].onclick();assert.match(status.textContent,/Remove a slice/);
choose([3,4,5,6]);assert.match(status.textContent,/Both plates work/);
reset.onclick();assert.equal(focused,0);assert(tiles.every(t=>t['aria-pressed']==='false'));assert.match(status.textContent,/no slices/);
console.log('PASS: two valid splits, each clue’s failure message, four-slice limit, collapsed guard and reset focus.');
